export function drillKindFor(card: SrsCard | undefined): "recall" | "cloze" | "contrast" {
  const reps = card?.repetitions ?? 0;
  if (reps <= 1) return "recall";
  if (reps === 2) return "cloze";
  return CONTRAST[card?.termId ?? ""] ? "contrast" : "cloze";
}

export function foilsFor(termId: string, kind: "contrast" | "cloze"): string[] {
  if (kind === "contrast") return CONTRAST[termId]?.foilIds ?? [];
  return CLOZE[termId]?.foilIds ?? [];
}
