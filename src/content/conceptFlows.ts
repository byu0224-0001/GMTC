/**
 * 검수된 개념 흐름.
 *
 * 왜 따로 두는가. 예전에는 `chain`에 적힌 관련 용어를 전부 화살표로 이어 보여 줬다.
 * 화살표는 사용자가 `A가 B를 일으킨다`로 읽는다. 그런데 그 관계 상당수는 인과가
 * 아니다. 대표적으로 이렇게 나갔다.
 *
 *     잠재GDP성장률 → GDP갭 → 물가 → 기준금리
 *
 * GDP갭은 잠재성장률이 일으키는 것이 아니라 **실제 GDP와 잠재 GDP의 차이**다.
 * 정의 관계를 인과처럼 가르치면 사용자가 잘못 배운다.
 *
 * 그래서 두 가지로 나눈다.
 *
 *   - 여기 적힌 흐름만 화살표로 보여 준다.
 *   - 나머지 관련 용어는 `같이 보면 좋은 개념` 칩으로만 보여 준다.
 *
 * ## note가 하는 일은 하나다
 *
 * 처음에는 note에 `그래서 이걸 어떻게 읽는지`까지 적었다. 그런데 그 해석은 바로
 * 위 해설이 이미 하고 있었다. 화면에서는 이렇게 보였다.
 *
 *     해설   적립 비율이 오르면 은행이 대출에 쓸 자금이 줄어들 수 있어요.
 *            다만 대출이 그 비율만큼 기계적으로 줄어드는 것은 아니라서…
 *     흐름   예금 → 지급준비금 적립 → 은행이 쓸 수 있는 자금
 *     note   적립 비율이 오르면 은행이 대출에 쓸 자금이 줄어들 수 있어요.
 *            다만 대출이 그 비율만큼 기계적으로 줄어드는 것은 아니에요.
 *
 * 같은 말을 두 번 읽힌 것이다. 12개 중 4개가 이 상태였다.
 *
 * 그래서 역할을 갈랐다. **해석은 해설이 한다. note는 이 화살표를 어떻게 읽는지만
 * 말한다.** 계산인지, 정의인지, 시간 순서인지, 영향인지를 밝히는 한두 문장이다.
 * note를 아예 없애는 방법도 있었지만, 그러면 화살표를 인과로 오독하는 것을 막을
 * 장치가 없어진다. 없애는 대신 좁혔다.
 */
export interface ConceptFlow {
  steps: string[];
  /**
   * 이 화살표를 어떻게 읽는지. 해석이 아니다.
   * 해석을 여기 적으면 위 해설과 같은 말이 된다.
   */
  note: string;
}

