def main() -> int:
    src = PATH.read_text(encoding="utf-8")
    ids = re.findall(r'\n    id: "(cx-[^"]+)"', src)
    missing: list[str] = []
    applied = 0

    for cid, pairs in EDITS.items():
        anchor = f'id: "{cid}",'
        if anchor not in src:
            missing.append(cid)
            continue
        start = src.index(anchor)
        end = src.index("answerTermId:", start)
        block = src[start:end]
        new_block = block
        for old, new in pairs:
            if old not in new_block:
                missing.append(f"{cid}: {old[:24]}…")
                continue
            new_block = new_block.replace(old, new, 1)
            applied += 1
        src = src[:start] + new_block + src[end:]

    if missing:
        print("MISSING:", *missing, sep="\n  ")
        return 1

    PATH.write_text(src, encoding="utf-8")

    blocks = re.split(r'\n  \{\n    id: "cx-', src)[1:]
    over = []
    without = []
    for cid, b in zip(ids, blocks):
        m = re.search(r'situation:\s*\n?\s*"((?:[^"\\]|\\.)*)"', b)
        body = m.group(1)
        if not 150 <= len(body) <= 400:
            over.append(f"{cid} {len(body)}")
        if not re.search(r"[0-9]", body):
            without.append(cid)
    print(f"applied {applied} edits to {len(EDITS)} cases")
    if over:
        print("LENGTH OUT OF RANGE:", over)
        return 1
    print("숫자 없는 편:", without or "없음")
    return 0


if __name__ == "__main__":
    sys.exit(main())
